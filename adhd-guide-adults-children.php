                <h3>What is ADHD?</h3>
                <p>ADHD is a neurodevelopmental disorder that affects how the brain regulates attention, impulse control, and activity levels. It's not about being lazy, unmotivated, or lacking intelligence—people with ADHD often have unique strengths including creativity, problem-solving abilities, and the capacity to hyperfocus on topics that interest them.</p>

                <p>ADHD typically begins in childhood, but many people aren't diagnosed until adolescence or adulthood. In fact, many adults discover they have ADHD after their child is diagnosed and they recognize similar patterns in themselves.</p>

                <h3>The Three Types of ADHD</h3>
                <h5>1. Predominantly Inattentive Type</h5>
                <p>People with this type have difficulty sustaining attention, following through on tasks, and organizing activities. They may appear dreamy, forgetful, or "spacey." This type is often missed, especially in girls and women.</p>

                <h5>2. Predominantly Hyperactive-Impulsive Type</h5>
                <p>Characterized by excessive physical activity, fidgeting, difficulty waiting, and acting without thinking. Children may be described as "always on the go" or having "no off switch."</p>

                <h5>3. Combined Type</h5>
                <p>The most common type, featuring significant symptoms of both inattention and hyperactivity-impulsivity.</p>

                <h3>ADHD Symptoms in Children</h3>
                <p>Children with ADHD may show the following signs:</p>
                <p><b>Inattention symptoms:</b></p>
                <p>&middot; Difficulty focusing on schoolwork or tasks</p>
                <p>&middot; Careless mistakes in homework or activities</p>
                <p>&middot; Appears not to listen when spoken to directly</p>
                <p>&middot; Trouble following instructions and finishing tasks</p>
                <p>&middot; Loses things necessary for activities (books, pencils, homework)</p>
                <p>&middot; Easily distracted by unrelated thoughts or stimuli</p>
                <p>&middot; Forgetful in daily activities</p>

                <p><b>Hyperactivity-impulsivity symptoms:</b></p>
                <p>&middot; Fidgets, squirms, or can't stay seated</p>
                <p>&middot; Runs or climbs in inappropriate situations</p>
                <p>&middot; Unable to play quietly</p>
                <p>&middot; Talks excessively</p>
                <p>&middot; Blurts out answers before questions are finished</p>
                <p>&middot; Difficulty waiting their turn</p>
                <p>&middot; Interrupts or intrudes on others</p>

                <h3>ADHD Symptoms in Adults</h3>
                <p>Adult ADHD often looks different than childhood ADHD. Common signs include:</p>
                <p>&middot; Chronic lateness and poor time management</p>
                <p>&middot; Difficulty completing projects at work</p>
                <p>&middot; Disorganization and cluttered spaces</p>
                <p>&middot; Trouble maintaining relationships</p>
                <p>&middot; Impulsive decision-making (spending, career changes)</p>
                <p>&middot; Restlessness and difficulty relaxing</p>
                <p>&middot; Low frustration tolerance and mood swings</p>
                <p>&middot; Hyperfocus on interesting tasks while neglecting others</p>
                <p>&middot; Forgetfulness with appointments and obligations</p>

                <h3>Why Get an ADHD Evaluation?</h3>
                <p>A proper ADHD evaluation is important because:</p>
                <p>&middot; Many conditions can mimic ADHD symptoms (anxiety, depression, sleep disorders, learning disabilities)</p>
                <p>&middot; Accurate diagnosis leads to appropriate treatment</p>
                <p>&middot; Schools and workplaces may require documentation for accommodations</p>
                <p>&middot; Understanding your brain helps with self-compassion and better strategies</p>

                <h3>What to Expect During ADHD Testing</h3>
                <p>At Healing Therapy Center, our comprehensive ADHD evaluation includes:</p>
                <p>&middot; <b>Clinical interview:</b> Detailed discussion of symptoms, history, and daily functioning</p>
                <p>&middot; <b>Rating scales:</b> Standardized questionnaires completed by the individual, parents, and/or teachers</p>
                <p>&middot; <b>Cognitive testing:</b> Assessment of attention, memory, and executive function</p>
                <p>&middot; <b>Rule-out evaluation:</b> Screening for other conditions that may cause similar symptoms</p>
                <p>&middot; <b>Comprehensive report:</b> Detailed findings and recommendations</p>

                <h3>Treatment Options for ADHD</h3>
                <p>Effective ADHD treatment often involves a combination of approaches:</p>

