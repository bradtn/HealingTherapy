                                    <h2>Signs Your Child May Need an Autism Evaluation</h2>
                                    <p>Every child develops differently, but certain patterns may indicate it's time to seek a professional evaluation. Consider scheduling an assessment if your child shows:</p>
                                    <ul>
                                        <li><strong>Social differences:</strong> Limited eye contact, difficulty making friends, or seeming uninterested in other children</li>
                                        <li><strong>Communication challenges:</strong> Delayed speech, repeating words or phrases, or difficulty with back-and-forth conversation</li>
                                        <li><strong>Repetitive behaviors:</strong> Hand flapping, rocking, lining up toys, or intense focus on specific interests</li>
                                        <li><strong>Sensory sensitivities:</strong> Strong reactions to sounds, textures, lights, or certain foods</li>
                                        <li><strong>Routine dependence:</strong> Significant distress when routines change</li>
                                    </ul>
                                    <p>If you're noticing these signs, our <a href="autism-screening-tool">free online autism screening tool</a> can help you determine if a full evaluation is recommended.</p>

                                    <h2>What Happens During an Autism Evaluation?</h2>
                                    <p>A comprehensive autism evaluation at our Dearborn clinic typically includes several components:</p>

                                    <h3>1. Parent/Caregiver Interview</h3>
                                    <p>We'll gather detailed information about your child's developmental history, current behaviors, and your specific concerns. This helps us understand your child's unique profile.</p>

                                    <h3>2. Direct Observation and Assessment</h3>
                                    <p>Our licensed psychologists use gold-standard assessment tools, including the ADOS-2 (Autism Diagnostic Observation Schedule), to observe your child's social communication, play, and behavior patterns.</p>

                                    <h3>3. Cognitive and Developmental Testing</h3>
                                    <p>We assess your child's intellectual functioning, language abilities, and adaptive skills to get a complete picture of their strengths and needs.</p>

                                    <h3>4. Feedback Session</h3>
                                    <p>You'll receive a thorough explanation of our findings, a formal diagnosis (if applicable), and personalized recommendations for therapy, school accommodations, and support services.</p>

                                    <h3>5. Written Report</h3>
                                    <p>We provide a comprehensive written report that you can share with schools, therapists, and other providers to help your child get the support they need.</p>

