                                    <h3 class="h6 mb-3">What's Included in the Evaluation</h3>
                                    <ol class="small mb-0">
                                        <li class="mb-3"><strong>Initial Consultation (60-90 minutes):</strong> Clinical interview with parent/caregiver (for children) or with the adult seeking evaluation. Developmental history, current concerns, family history.</li>
                                        <li class="mb-3"><strong>ADOS-2 Assessment (90-120 minutes):</strong> The Autism Diagnostic Observation Schedule, Second Edition - the gold standard for autism diagnosis. Structured play and social interaction tasks designed to elicit autism-related behaviors.</li>
                                        <li class="mb-3"><strong>ADI-R Interview (2-3 hours):</strong> Autism Diagnostic Interview-Revised - comprehensive structured interview about developmental history and current functioning.</li>
                                        <li class="mb-3"><strong>Cognitive Testing (2-3 hours):</strong> IQ testing to understand cognitive strengths and challenges, learning profile, and rule out intellectual disability.</li>
                                        <li class="mb-3"><strong>Behavioral Rating Scales:</strong> Questionnaires completed by parents, teachers (for children), or self-report (for adults) to gather comprehensive information.</li>
                                        <li class="mb-0"><strong>Comprehensive Report & Feedback (60 minutes):</strong> Detailed written report with diagnosis, scores, recommendations for therapy, school accommodations (IEP/504), and workplace accommodations. Feedback session to explain findings and answer questions.</li>
