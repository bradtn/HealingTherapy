                                        <p>Seek immediate help if you experience:</p>
                                        <ul class="mb-2">
                                            <li>Thoughts of suicide or ending your life</li>
                                            <li>Plans to hurt yourself or others</li>
                                            <li>Using alcohol or drugs to cope</li>
                                            <li>Panic attacks that impair your ability to work</li>
                                            <li>Unsafe behavior on or off duty</li>
                                        </ul>
                                        <p class="mb-0"><strong>Call 988 (Suicide & Crisis Lifeline) or go to the nearest emergency room. Your life matters.</strong></p>
