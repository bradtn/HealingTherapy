                                        <p class="mb-2">If you're experiencing any of these, seek help right away:</p>
                                        <ul class="mb-0">
                                            <li>Thoughts of suicide or self-harm</li>
                                            <li>Panic attacks that interfere with work or daily life</li>
                                            <li>Using alcohol or drugs to cope with stress</li>
                                            <li>Unable to get out of bed or complete basic self-care</li>
