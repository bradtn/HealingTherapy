<h2 class="mt-4">Depression vs. Sadness: When to Seek Help</h2>
<p>Everyone feels sad sometimes. Depression is different - it's intense, persistent, and interferes with your ability to function. Seek professional help if:</p>
<ul>
    <li>Sad or empty mood lasting most of the day, nearly every day for 2+ weeks</li>
    <li>Loss of interest or pleasure in activities you used to enjoy</li>
    <li>Significant changes in appetite, weight, or sleep</li>
    <li>Fatigue or loss of energy nearly every day</li>
    <li>Feelings of worthlessness or excessive guilt</li>
    <li>Difficulty concentrating, thinking, or making decisions</li>
    <li>Thoughts of death or suicide</li>
    <li>Depression interfering with work, school, relationships, or daily activities</li>
</ul>

<h2 class="mt-4">Medication vs. Therapy vs. Both</h2>
<p><strong>Therapy alone</strong> is effective for mild to moderate depression. CBT has similar effectiveness to antidepressants without side effects.</p>
<p><strong>Medication alone</strong> can be helpful, especially for severe depression, but doesn't teach coping skills. Depression often returns when medication is stopped.</p>
<p><strong>Combination treatment</strong> (therapy + medication) is most effective for moderate to severe depression, offering symptom relief plus long-term coping skills.</p>

<h2 class="mt-4">How Depression Therapy Works</h2>
<p>In the first session, we'll discuss your depression symptoms, history, current stressors, and goals. Together we'll develop a personalized treatment plan.</p>

<p>Therapy typically involves understanding depression patterns, identifying triggers, challenging negative thoughts, increasing positive activities, improving sleep and self-care, and developing relapse prevention strategies.</p>

<p>Most people attend weekly 50-minute sessions for 12-20 weeks. Many notice improvement within the first month, though full recovery takes longer. The skills learned in therapy help prevent future depression episodes.</p>

